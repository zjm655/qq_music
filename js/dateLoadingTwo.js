//divStringTwo是新歌首发的渲染函数，也是把对应内容结合html标签平成一个大字符串，然后插入html里
function divStringTwo(dateGodownTwo){
    let carouselDiv="";
    for(let i=0;i<dateGodownTwo.length;i++){
        carouselDiv += `
<div class="contmusicTwo Center">`;
        for(let j=0;j<dateGodownTwo[i].length;j++){
            carouselDiv += 
`<div class="outboxTwo">
    <div class="innerboxTwo">
        <img src="${dateGodownTwo[i][j].imgSrc}" loading="lazy" decoding="async" alt="cover" width="86px" height="86px">
        <div class="markTwo maskTwo"></div>
    </div>
    <div class="divp">
        <p><a href="" class="guidecontent guideBottom midtip">${dateGodownTwo[i][j].title}</a></p>
        <p class="views">${dateGodownTwo[i][j].author}</p>
    </div>
    <p class="views">${dateGodownTwo[i][j].time}</p>
</div>`;
        }
        carouselDiv +=`</div>`;
    }
    return carouselDiv;
}
